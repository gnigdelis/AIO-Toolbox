# ============================================================================
# SVG CREATION
# ============================================================================


def _svg(
    name: str,
    color: str,
) -> str:

    path = _ICON_PATHS.get(
        name
    )

    if path is None:
        raise ValueError(
            f"Unknown AIO Toolbox icon: {name}"
        )

    return f"""
    <svg
        xmlns="http://www.w3.org/2000/svg"
        width="24"
        height="24"
        viewBox="0 0 24 24"
        fill="none"
        stroke="{color}"
        stroke-width="2.0"
        stroke-linecap="round"
        stroke-linejoin="round"
    >
        {path}
    </svg>
    """


# ============================================================================
# COLOR NORMALIZATION
# ============================================================================


def _normalize_color(
    color: str,
) -> str:
    """
    Normalize the old multi-color sidebar palette.

    The existing MainWindow still passes different colors for different
    navigation icons. We intentionally collapse those colors into the
    single blue used by the locked sidebar reference.

    White remains white because the selected Home item uses white.
    """

    normalized = color.strip().upper()

    if normalized in {
        "#18A96B",
        "#F2994A",
        "#E05A47",
        "#7A62D3",
        "#2D9CDB",
        "#6F4BB8",
        "#D99A16",
        "#2676D9",
        "#1E9A8A",
        "#7B61B8",
        "#26344D",
        "#3F6495",
    }:
        return SIDEBAR_BLUE

    if normalized in {
        "#FFFFFF",
        "#FFF",
    }:
        return "#FFFFFF"

    return color


# ============================================================================
# PIXMAP RENDERING
# ============================================================================


@lru_cache(
    maxsize=512
)
def _render_pixmap(
    name: str,
    color: str,
    size: int,
) -> QPixmap:

    color = _normalize_color(
        color
    )

    renderer = QSvgRenderer(
        QByteArray(
            _svg(
                name,
                color,
            ).encode(
                "utf-8"
            )
        )
    )

    result = QPixmap(
        size,
        size,
    )

    result.fill(
        Qt.GlobalColor.transparent
    )

    painter = QPainter(
        result
    )

    try:
        renderer.render(
            painter
        )

    finally:
        painter.end()

    return result


# ============================================================================
# PUBLIC API
# ============================================================================


def pixmap(
    name: str,
    color: str = SIDEBAR_BLUE,
    size: int = 20,
) -> QPixmap:

    return _render_pixmap(
        name,
        color,
        size,
    )


def icon(
    name: str,
    color: str = SIDEBAR_BLUE,
    size: int = 20,
) -> QIcon:

    return QIcon(
        _render_pixmap(
            name,
            color,
            size,
        )
    )